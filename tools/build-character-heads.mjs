#!/usr/bin/env node
// Generate js/characters.js — the character art the app renders — from
// design/anim-characters.js (itself generated from characters.html). Two maps:
//   CHARACTER_HEADS  — head-only views for dialogue bubbles (SR-01/SR-07)
//   CHARACTER_BODIES — whole-body views for the decorative path companions (SR-07)
// Re-run after editing character art: node tools/build-character-heads.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

globalThis.window = {};
// eslint-disable-next-line no-eval
eval(readFileSync(join(ROOT, 'design/anim-characters.js'), 'utf8'));
const chars = globalThis.window.ANIM_CHARACTERS;

const mapLiteral = (pick) => chars.map((c) => `\t${JSON.stringify(c.id)}: ${JSON.stringify(pick(c))},`).join('\n');
const out = `// Character art the app renders. AUTO-GENERATED by tools/build-character-heads.mjs
// from design/anim-characters.js — do not edit by hand. Each value is a self-contained
// <svg> using the .f-* fill classes (Sano's live in css/sano.css; the companion palette
// was ported there too) and the .part-* groups the idle / tap animations target.
//   CHARACTER_HEADS  — head-only (viewBox 0 0 200 200), used in dialogue bubbles.
//   CHARACTER_BODIES — whole-body, used as the decorative companions along the path.
const CHARACTER_HEADS = {
${mapLiteral((c) => c.head)}
};
const CHARACTER_BODIES = {
${mapLiteral((c) => c.whole)}
};
`;

writeFileSync(join(ROOT, 'js/characters.js'), out);
console.log('wrote js/characters.js with', chars.length, 'heads + bodies:', chars.map((c) => c.id).join(', '));
