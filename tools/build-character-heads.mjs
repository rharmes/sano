#!/usr/bin/env node
// Generate js/characters.js — the head-only character art used in dialogue bubbles
// (SR-07) — from design/anim-characters.js (itself generated from characters.html).
// Re-run after editing character art: node tools/build-character-heads.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

globalThis.window = {};
// eslint-disable-next-line no-eval
eval(readFileSync(join(ROOT, 'design/anim-characters.js'), 'utf8'));
const chars = globalThis.window.ANIM_CHARACTERS;

const entries = chars.map((c) => `\t${JSON.stringify(c.id)}: ${JSON.stringify(c.head)},`).join('\n');
const out = `// Head-only character art for dialogue bubbles (SR-01/SR-07). AUTO-GENERATED by
// tools/build-character-heads.mjs from design/anim-characters.js — do not edit by hand.
// Each value is a self-contained <svg viewBox="0 0 200 200"> using the .f-* fill
// classes (Sano's live in css/sano.css; the companion palette was ported there too).
const CHARACTER_HEADS = {
${entries}
};
`;

writeFileSync(join(ROOT, 'js/characters.js'), out);
console.log('wrote js/characters.js with', chars.length, 'character heads:', chars.map((c) => c.id).join(', '));
