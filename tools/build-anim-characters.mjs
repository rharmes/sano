// Generate design/anim-characters.js from design/characters.html.
//
// The animation tuner (design/animations.html) drives each character's parts by
// CSS class (.part-head/-tail/-eyes/-ear/-nose). characters.html is the single
// source of truth for the companion art; this script lifts each character's two
// views out of it and records which parts are present, so the tuner never drifts
// from the gallery. Re-run after editing companion art:
//
//   node tools/build-anim-characters.mjs
//
// Sano is NOT here — its art lives inline in animations.html (and index.html),
// not in the companions gallery.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'design', 'characters.html');
const OUT = join(root, 'design', 'anim-characters.js');

const html = readFileSync(SRC, 'utf8');

// Whole-body vs head view is encoded in the aria-label's second word.
const WHOLE_WORDS = new Set(['sitting', 'standing', 'sprawl']);
const HEAD_WORDS = new Set(['face', 'head']);
const PART_CLASSES = ['head', 'tail', 'eyes', 'ear', 'nose'];

// Pull the <svg …aria-label="LABEL">…</svg> that owns a given label.
function svgFor(label) {
	const at = html.indexOf(`aria-label="${label}"`);
	if (at < 0) return null;
	const start = html.lastIndexOf('<svg', at);
	const end = html.indexOf('</svg>', at) + 6;
	return html.slice(start, end);
}

function partsIn(...svgs) {
	const found = new Set();
	for (const svg of svgs) {
		if (!svg) continue;
		for (const p of PART_CLASSES) {
			if (new RegExp(`\\bpart-${p}\\b`).test(svg)) found.add(p);
		}
	}
	return PART_CLASSES.filter((p) => found.has(p)); // stable order
}

// Walk every aria-label in document order, grouping by character (first word).
const order = [];
const byId = new Map();
const re = /aria-label="([^"]+)"/g;
let m;
while ((m = re.exec(html))) {
	const label = m[1];
	const [name, view] = label.split(' ');
	const id = name.toLowerCase();
	if (!byId.has(id)) {
		byId.set(id, { id, name, whole: null, head: null });
		order.push(id);
	}
	const entry = byId.get(id);
	if (WHOLE_WORDS.has(view)) entry.whole = svgFor(label);
	else if (HEAD_WORDS.has(view)) entry.head = svgFor(label);
}

const characters = order.map((id) => {
	const e = byId.get(id);
	return { id: e.id, name: e.name, whole: e.whole, head: e.head, parts: partsIn(e.whole, e.head) };
});

const banner =
	'// AUTO-GENERATED by tools/build-anim-characters.mjs — do not edit by hand.\n' +
	'// Source: design/characters.html. Re-run after editing companion art.\n';
writeFileSync(OUT, banner + 'window.ANIM_CHARACTERS = ' + JSON.stringify(characters, null, '\t') + ';\n');

console.log(`Wrote ${OUT} — ${characters.length} characters:`);
for (const c of characters) {
	const miss = [c.whole ? '' : 'NO-WHOLE', c.head ? '' : 'NO-HEAD'].filter(Boolean).join(' ');
	console.log(`  ${c.name.padEnd(10)} parts: [${c.parts.join(', ') || '—'}] ${miss}`);
}
